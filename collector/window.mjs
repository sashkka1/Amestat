// Закрытие окна расчёта выплат (миграция v38).
//
// Зачем. Деньги креатору считаются по просмотрам на отметке «публикация + окно» (по умолчанию
// 72 часа), а берётся первый снимок НА отметке или после неё. Обход ходит два раза в сутки,
// поэтому снимок приходит с запозданием: по живым данным 19.09 ни одно видео не легло ровно в
// 72 часа — 74, 75, 76, 78, а одно и вовсе 90 (отметка пришлась на ночь, компьютер был
// выключен). Лишние часы просмотров попадали в выплату.
//
// Что делаем. Резидент раз в несколько минут спрашивает базу, у кого окно только что
// закрылось, и обходит этих креаторов коротким заходом. Тогда снимок ложится рядом с отметкой,
// и в выплату идут ровно те просмотры, за которые договаривались.
//
// ⚠️ Про таблицы оплаты сборщик по-прежнему не знает ничего: он видит одну функцию
// `payment_window_due`, а ставки, платежи и покрытия остаются делом сайта.

import { get } from "./db.mjs";

/** Сколько часов после отметки ещё имеет смысл гнаться за видео отдельным заходом. */
export const MAX_AGE_HOURS = 24;

/**
 * Не чаще раза в час на креатора. Без этого неудачный заход (капча, защита по адресу, пустой
 * список) снимка не ставит, и через пять минут тот же креатор снова «пора» — петля, которая
 * сама и вызвала бы защиту TikTok по адресу. Не закрылось за час — закроет обычный обход.
 */
export const RETRY_MS = 60 * 60_000;

/**
 * Строки функции базы → заходы, по одному на креатора.
 *
 * ⚠️ Чистая: базы не знает, время приходит параметром `now`. Два видео одного креатора закрываются ОДНИМ обходом — второй
 * заход подряд к тому же аккаунту TikTok отвечает пустотой, и ради второго ролика ломать
 * первый нельзя. Порядок — от самой старой отметки: она дольше всех ждёт.
 * `limit` держит очередь короткой: лимит запусков чистого профиля TikTok общий на компьютер
 * (`tiktok-gate.mjs`), и вываливать в него десяток заходов разом незачем — остальные подхватит
 * следующая проверка.
 * `tried` — когда к креатору уже ходили этим путём (id → миллисекунды); такие пропускаются,
 * пока не пройдёт `cooldownMs`.
 */
export function dueRuns(rows, limit = 3, { tried = new Map(), now = Date.now(), cooldownMs = RETRY_MS } = {}) {
  const byCreator = new Map();
  for (const r of rows ?? []) {
    if (!r?.creator_id) continue;
    const seen = byCreator.get(r.creator_id);
    if (seen) {
      seen.videos += 1;
      if (r.mark_at < seen.markAt) seen.markAt = r.mark_at;
      continue;
    }
    byCreator.set(r.creator_id, {
      creatorId: r.creator_id,
      handle: r.handle ?? "",
      platform: r.platform ?? "",
      videos: 1,
      markAt: r.mark_at,
    });
  }
  return [...byCreator.values()]
    .filter((r) => {
      const at = tried.get(r.creatorId);
      return at === undefined || now - at >= cooldownMs;
    })
    .sort((a, b) => String(a.markAt).localeCompare(String(b.markAt)))
    .slice(0, Math.max(limit, 0));
}

/** У кого окно закрылось и снимка после отметки ещё нет. Ошибку бросает наверх. */
export async function windowDue(maxAgeHours = MAX_AGE_HOURS) {
  return await get(`rpc/payment_window_due?p_max_age_hours=${maxAgeHours}`);
}
