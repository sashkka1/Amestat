-- v24: оценка объёма обхода и прогноз конца.
-- Владелец, 2026-09-09: «сначала одним заходом оценить объём работы (число видео и т. п.), а
-- потом показывать маленький график 0–100 %, насколько мы близки к завершению — „6 из 10
-- креаторов“ ничего не говорит: может, прошли шесть самых быстрых».
--
-- Единица работы — СЕКУНДА по калибровке сборщика (`collector/estimate.mjs`,
-- `collector/logs/timing-state.json`): только в секундах шаг списка у одного креатора и шаг
-- комментариев у другого складываются в одну шкалу. `work_total` считается ДО первого браузера
-- по тому, что уже лежит в базе (число видео, их даты, наши и жёлтые, счётчики комментариев);
-- `work_done` растёт после каждого шага, а не после каждого креатора.
--
-- ⚠️ Оценка завышена сверху: видео, у которых комментарии не изменились с прошлого раза, шаг
-- пропустит, но узнать их заранее нельзя. Полоса, доезжающая до конца раньше, лучше стоящей.

alter table public.sync_runs
  add column work_total numeric,
  add column work_done numeric,
  add column eta_at timestamptz,
  add column estimate jsonb;

comment on column public.sync_runs.work_total is 'Оценка всего обхода в секундах по калибровке сборщика; null — оценить не вышло.';
comment on column public.sync_runs.work_done is 'Сколько этих секунд уже отработано: сумма оценок пройденных шагов, а не настенное время.';
comment on column public.sync_runs.eta_at is 'Когда обход ожидается законченным. Считается по полосам: остаток каждой отдельно, итог — самая долгая.';
comment on column public.sync_runs.estimate is 'Разбивка оценки по креаторам: [{handle, list, comments, replies, done}] в секундах.';
